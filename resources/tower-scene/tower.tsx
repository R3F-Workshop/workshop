/** Builds an antenna member anchored at the tower summit. */
function makeAntennaGeometry({ kind, y, size: [rt, rb, h] }: AntennaPart) {
  const g = new THREE.CylinderGeometry(rt, rb, h, kind === "arms" ? 8 : 12);
  if (kind === "mast") {
    g.translate(0, h / 2 - ANTENNA_ROOT, 0);
  } else if (kind === "collar") {
    g.translate(0, y, 0);
  } else {
    // Lay each arm flat before rendering it in a crossed pair.
    g.rotateZ(Math.PI / 2);
    g.translate(0, y, 0);
  }
  return g;
}

function Beacon({
  lightLevel,
  speed = 0.6,
}: {
  lightLevel: THREE.UniformNode<"float", number>;
  speed?: number;
}) {
  const spinRef = useRef<THREE.Group>(null);

  const geometry = useMemo(() => {
    // High radial segmentation on purpose: the anglePower falloff shades by
    // interpolated silhouette normals, and a coarse tube shows facets.
    const g = new THREE.CylinderGeometry(
      BEAM_FLARE,
      1.5,
      BEAM_LENGTH,
      64,
      8,
      true,
    );
    // Hub end at the origin, beam extending along +y (then rotated flat).
    g.translate(0, BEAM_LENGTH / 2, 0);
    return g;
  }, []);

  const createBeamNodes = useCallback(
    () => makeBeamNodes(lightLevel),
    [lightLevel],
  );
  // Both beams share one graph and light uniform.
  const beam = useLocalNodes(createBeamNodes);

  useFrame((_, delta) => {
    if (spinRef.current) spinRef.current.rotation.y += delta * speed;
  });

  return (
    <group ref={spinRef}>
      {[-Math.PI / 2, Math.PI / 2].map((roll) => (
        <mesh key={roll} geometry={geometry} rotation-z={roll}>
          <meshBasicNodeMaterial
            color="#ffeec2"
            transparent
            blending={THREE.AdditiveBlending}
            side={THREE.DoubleSide}
            depthWrite={false}
            opacityNode={beam.opacityNode}
          />
        </mesh>
      ))}
    </group>
  );
}

