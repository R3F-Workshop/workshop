export type TowerMode = "glow" | "metal" | "sparkle";

/**
 * The sparkle: the real tower's 20,000 bulbs going off for five minutes on
 * the hour, compressed into a permanent state.
 *
 * All in the fragment shader, driven by `TSL.time`: local space is diced
 * into cells, each cell gets a stable hash, and each hash phase-offsets a
 * shared slow cycle so a cell pops for a few tens of ms and stays dark for
 * the rest of it. The pops write to `emissiveNode`, which the pipeline's
 * emissive MRT attachment feeds straight into bloom — that's the glitter.
 * The base material is the dark iron the tower actually is at dusk.
 */
function makeSparkleNodes(
  lightLevel: THREE.UniformNode<"float", number>,
) {
  const cell = TSL.floor(TSL.positionLocal.mul(0.9));
  const seed = TSL.fract(
    TSL.sin(cell.dot(TSL.vec3(127.1, 311.7, 74.7))).mul(43758.5453),
  );
  // Every cell runs the same 2.5s cycle at a private phase; the step keeps
  // ~1.5% of it lit, so at any instant a sparse random scatter is popping.
  const cycle = TSL.fract(TSL.time.mul(0.4).add(seed));
  const flash = TSL.step(0.985, cycle);
  const brightness = seed.mul(0.6).add(0.4);

  return {
    emissiveNode: TSL.color("#fff3d0").mul(
      flash.mul(brightness).mul(8).mul(lightLevel),
    ),
  };
}

/**
 * The summit beacon: two opposed fake-volumetric beams, shaded the way
 * drei's `<SpotLight volumetric>` (pmndrs volumetric-spotlight example)
 * does its cone — a TSL port of that GLSL SpotLightMaterial, which can't
 * run on WebGPU directly. Two terms multiply:
 *
 * 1. Linear distance attenuation from the hub along the beam.
 * 2. `anglePower` falloff on the view-space normal: silhouette-edge
 *    fragments (normal ⟂ view) fade out, the tube's core (normal toward
 *    camera) stays bright. This is what turns a hard-edged cone into a
 *    soft light shaft with a luminous core.
 *
 * The example's third trick — depth-buffer soft intersection — is skipped:
 * these beams live in the sky and rarely cross geometry. Additive, no
 * depth write, double-sided (abs() covers the flipped back-face normals).
 */
function makeBeamNodes(lightLevel: THREE.UniformNode<"float", number>) {
  // Geometry below is translated so the hub is at y = 0, beam along +y.
  const along = TSL.positionLocal.y.div(BEAM_LENGTH).clamp(0.0, 1.0);
  const distanceFade = TSL.oneMinus(along);
  const angleFade = TSL.pow(TSL.abs(TSL.normalView.z), 4.0);
  return {
    opacityNode: distanceFade.mul(angleFade).mul(0.6).mul(lightLevel),
  };
}

